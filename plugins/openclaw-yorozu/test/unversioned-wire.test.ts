import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { test } from "node:test";

registerHooks({
  resolve(specifier, context, next) {
    if (specifier.startsWith("./") && specifier.endsWith(".js") && context.parentURL) {
      const ts = new URL(specifier.replace(/\.js$/, ".ts"), context.parentURL);
      if (existsSync(ts)) return next(ts.href, context);
    }
    return next(specifier, context);
  },
});
const { acceptHandshake, b64u, decodeFrame, ed25519Keypair, signFrame, x25519Keypair } = await import("../src/wire.ts");

// Generated by Swift ClientHandshake; UnversionedWireTests also finishes this exact response.
const vector = JSON.parse(readFileSync(new URL(
  "../../../packages/YorozuWire/Tests/YorozuWireTests/Fixtures/unversioned-wire.json", import.meta.url,
), "utf8"));

test("Swift unversioned init is accepted with yorozu prologue and answered in unversioned format", () => {
  const host = x25519Keypair(Buffer.alloc(32, 1));
  const signing = ed25519Keypair(Buffer.alloc(32, 2));
  const payload = b64u(Buffer.from(vector.initHex, "hex"));
  const accepted = acceptHandshake({
    host, room: "wire-test-room", payload, sig: signFrame(signing.privateKey, payload),
    now: 1_700_000_000_000, ephemeral: Buffer.alloc(32, 5),
  });
  assert.ok(accepted);
  assert.deepEqual(accepted.deviceStatic, x25519Keypair(Buffer.alloc(32, 3)).publicKey);
  assert.deepEqual(accepted.payload, { ts: 1_700_000_000_000 });
  const response = Buffer.from(accepted.response, "base64url");
  assert.equal(response[0], 0x12);
  assert.equal(response.toString("hex"), vector.responseHex);
  const decoded = decodeFrame(accepted.response);
  assert.ok(decoded?.type === "response");
  assert.equal(decoded.legacy, false);
});
